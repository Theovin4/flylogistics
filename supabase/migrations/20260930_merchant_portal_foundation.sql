create table if not exists public.merchant_recipients (
  id bigint generated by default as identity primary key,
  business_account_id bigint not null references public.business_accounts(id) on delete cascade,
  name text not null,
  phone text not null,
  email text,
  address text not null,
  city text not null,
  state text not null,
  country text not null default 'Nigeria',
  notes text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists merchant_recipients_account_created_idx
  on public.merchant_recipients (business_account_id, created_at desc);
create index if not exists merchant_recipients_account_phone_idx
  on public.merchant_recipients (business_account_id, phone);

alter table public.merchant_recipients enable row level security;
revoke all on table public.merchant_recipients from anon;
revoke all on table public.merchant_recipients from authenticated;
grant select, insert, update, delete on table public.merchant_recipients to authenticated;
grant all on table public.merchant_recipients to service_role;

drop policy if exists "merchant recipients member read" on public.merchant_recipients;
create policy "merchant recipients member read"
on public.merchant_recipients for select
to authenticated
using (
  exists (
    select 1
    from public.business_account_members member
    where member.business_account_id = public.merchant_recipients.business_account_id
      and member.user_id = (select auth.uid())
      and lower(coalesce(member.status, 'active')) = 'active'
  )
);

drop policy if exists "merchant recipients operations manage" on public.merchant_recipients;
create policy "merchant recipients operations manage"
on public.merchant_recipients for all
to authenticated
using (
  exists (
    select 1
    from public.business_account_members member
    where member.business_account_id = public.merchant_recipients.business_account_id
      and member.user_id = (select auth.uid())
      and lower(coalesce(member.status, 'active')) = 'active'
      and lower(coalesce(member.role, 'member')) in ('owner', 'admin', 'operations')
  )
)
with check (
  exists (
    select 1
    from public.business_account_members member
    where member.business_account_id = public.merchant_recipients.business_account_id
      and member.user_id = (select auth.uid())
      and lower(coalesce(member.status, 'active')) = 'active'
      and lower(coalesce(member.role, 'member')) in ('owner', 'admin', 'operations')
  )
);

