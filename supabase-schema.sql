-- Atomic, idempotent wallet settlement. Only the server-side service role may
-- execute this function; client roles cannot mutate balances directly.
create or replace function public.apply_customer_wallet_transaction(
  p_reference text,
  p_status text,
  p_provider_reference text default null
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_tx public.wallet_transactions%rowtype;
  v_wallet public.customer_wallets%rowtype;
  v_delta numeric;
  v_status text := upper(trim(coalesce(p_status, '')));
begin
  if v_status not in ('COMPLETED', 'FAILED', 'CANCELLED') then
    raise exception 'Unsupported wallet transaction status';
  end if;

  select * into v_tx
  from public.wallet_transactions
  where reference = p_reference
  for update;

  if not found then raise exception 'Wallet transaction not found'; end if;
  if v_tx.status <> 'PENDING' then
    return;
  end if;

  if v_status = 'COMPLETED' then
    select * into v_wallet
    from public.customer_wallets
    where id = v_tx.wallet_id
    for update;
    if not found then raise exception 'Customer wallet not found'; end if;

    v_delta := case when lower(v_tx.transaction_type) = 'debit'
      then -abs(v_tx.amount) else abs(v_tx.amount) end;
    if coalesce(v_wallet.balance, 0) + v_delta < 0 then
      raise exception 'Insufficient wallet balance';
    end if;

    update public.customer_wallets
    set balance = coalesce(balance, 0) + v_delta,
        updated_at = now()
    where id = v_tx.wallet_id;
  end if;

  update public.wallet_transactions
  set status = v_status,
      provider_reference = coalesce(p_provider_reference, provider_reference),
      completed_at = case when v_status = 'COMPLETED' then now() else completed_at end
  where id = v_tx.id;

  return;
end;
$$;

