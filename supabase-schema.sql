create or replace function public.handle_new_fly_user()
returns trigger
language plpgsql
security definer
set search_path = public
as '
declare
  requested_role text := lower(coalesce(new.raw_user_meta_data ->> ''role'', ''customer''));
  safe_role text := case when requested_role = ''driver'' then ''driver'' else ''customer'' end;
  linked_driver_id bigint;
begin
  if safe_role = ''driver'' then
    insert into public.drivers (
      name,
      status,
      phone,
      latitude,
      longitude,
      approval_status,
      account_user_id,
      offline_since,
      last_seen_at
    )
    values (
      coalesce(nullif(new.raw_user_meta_data ->> ''full_name'', ''''), new.email, ''Fly Driver''),
      ''offline'',
      nullif(new.raw_user_meta_data ->> ''phone'', ''''),
      6.5244,
      3.3792,
      ''pending'',
      new.id,
      now(),
      now()
    )
    returning id into linked_driver_id;
  end if;

  insert into public.user_profiles (id, email, full_name, company, phone, role, driver_id)
  values (
    new.id,
    new.email,
    nullif(new.raw_user_meta_data ->> ''full_name'', ''''),
    nullif(new.raw_user_meta_data ->> ''company'', ''''),
    nullif(new.raw_user_meta_data ->> ''phone'', ''''),
    safe_role,
    linked_driver_id
  )
  on conflict (id) do update set
    email = excluded.email,
    full_name = coalesce(excluded.full_name, public.user_profiles.full_name),
    company = coalesce(excluded.company, public.user_profiles.company),
    phone = coalesce(excluded.phone, public.user_profiles.phone),
    role = case when public.user_profiles.role in (''admin'', ''dispatcher'') then public.user_profiles.role else excluded.role end,
    driver_id = coalesce(public.user_profiles.driver_id, excluded.driver_id),
    updated_at = now();

  return new;
end;
';

