create or replace function public.can_access_fly_shipment(shipment_tracking_id text)
returns boolean
language sql
stable
security definer
set search_path = public
as '
  select exists (
    select 1
    from public.shipments shipment
    where shipment.tracking_id = shipment_tracking_id
      and (
        public.current_fly_role() in (''admin'', ''dispatcher'')
        or lower(coalesce(shipment.customer_email, '''')) = public.current_fly_email()
        or shipment.driver_id = public.current_fly_driver_id()
      )
  )
';

